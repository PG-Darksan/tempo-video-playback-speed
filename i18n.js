  /** 手動で選べる言語。表示名は各言語の自称で、翻訳しない。 */
  const LANGUAGES = Object.freeze([
    ['ja', '日本語'],
    ['en', 'English'],
    ['ko', '한국어'],
    ['zh_CN', '简体中文'],
    ['zh_TW', '繁體中文'],
    ['es', 'Español'],
    ['fr', 'Français'],
    ['de', 'Deutsch'],
    ['pt_BR', 'Português (Brasil)'],
    ['ru', 'Русский'],
    ['hi', 'हिन्दी'],
    ['ar', 'العربية']
  ]);
  const CODES = Object.freeze(LANGUAGES.map(([code]) => code));
  const RTL = new Set(['ar']);
  const FALLBACK = 'en';
  const TRADITIONAL_CHINESE = new Set(['tw', 'hk', 'mo', 'hant']);

  function browserLanguage() {
    try {
      if (root.chrome && chrome.i18n && typeof chrome.i18n.getUILanguage === 'function') {
        return chrome.i18n.getUILanguage();
      }
    } catch (_) {
      // 拡張機能の文脈が失われた content script など
    }
    return (root.navigator && root.navigator.language) || FALLBACK;
  }

  /** BCP 47 などの言語タグを、対応する12言語のどれかへ解決する。未対応は英語。 */
  function resolveTag(tag) {
    const parts = String(tag || '').replace(/_/g, '-').toLowerCase().split('-').filter(Boolean);
    const base = parts[0] || '';
    if (base === 'zh') {
      return parts.slice(1).some((p) => TRADITIONAL_CHINESE.has(p)) ? 'zh_TW' : 'zh_CN';
    }
    if (base === 'pt') return 'pt_BR';
    if (CODES.includes(base)) return base;
    return FALLBACK;
  }

  /** 保存値の検証。未保存・不正は 'auto'。 */
  function sanitizePreference(value) {
    return value === 'auto' || CODES.includes(value) ? value : 'auto';
  }

  /** 設定値（'auto' または言語コード）から表示言語を決める。 */
  function resolve(preference) {
    const pref = sanitizePreference(preference);
    return pref === 'auto' ? resolveTag(browserLanguage()) : pref;
  }

  /**
   * 翻訳文を返す。$NAME$ を params.name で置換する。
   * 見つからないときは英語、それも無ければ空文字（キー名は表示しない）。
   */
  function t(lang, key, params) {
    let message = CATALOGS[lang] && CATALOGS[lang][key];
    if (typeof message !== 'string' || message === '') {
      message = CATALOGS[FALLBACK] && CATALOGS[FALLBACK][key];
    }
    if (typeof message !== 'string') return '';
    if (params) {
      message = message.replace(/\$([A-Za-z0-9_]+)\$/g, (match, name) => {
        const value = params[name.toLowerCase()];
        return value == null ? match : String(value);
      });
    }
    return message;
  }

  function dir(lang) {
    return RTL.has(lang) ? 'rtl' : 'ltr';
  }

  /** HTML の lang 属性用（zh_TW → zh-TW）。 */
  function htmlLang(lang) {
    return String(lang).replace(/_/g, '-');
  }

  root.TempoI18n = Object.freeze({
    LANGUAGES,
    CODES,
    FALLBACK,
    browserLanguage,
    resolveTag,
    sanitizePreference,
    resolve,
    t,
    dir,
    htmlLang
  });
